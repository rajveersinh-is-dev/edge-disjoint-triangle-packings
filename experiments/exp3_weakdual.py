"""Experiment 3: the weak-dual reduction for convex position.

Two structural claims under test.

(L1) Every 3-cycle of a triangulation T of the convex n-gon is a *face* of T.
     (Consequence: nu(P) = max over triangulations of alpha(weak dual) when P
     is in convex position.)

(L2) Every subcubic tree on N vertices is the weak dual of some triangulation of
     the convex (N+2)-gon.
     (Consequence: f(n) = max { alpha(T) : T subcubic tree on n-2 vertices }
                       = a(n-2).)

We enumerate all triangulations for n <= 10, compute their weak duals, and check
L1 by counting 3-cycles against faces.  For L2 we collect the set of weak duals
obtained and compare it with the set of all subcubic trees on n-2 vertices
(generated by exhaustive search).
"""

from __future__ import annotations

import csv
import itertools
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from planetri.convex import (
    CATALAN,
    convex_nu_closed_form,
    convex_nu_dp,
    enumerate_triangulations,
    triangulation_triangle_count,
)
from planetri.trees import alpha_max_subcubic, alpha_tree, weak_dual

RESULTS = os.path.join(os.path.dirname(__file__), "results")
N_MAX_ENUM = 10
N_MAX_TREE = 8


def all_subcubic_trees(N: int) -> set[tuple[tuple[int, int], ...]]:
    """Every labelled tree on {0..N-1} with maximum degree <= 3, as an edge set."""
    out = set()
    seen_vertices = set()

    def rec(edges, verts):
        if len(verts) == N:
            out.add(tuple(sorted((min(a, b), max(a, b)) for a, b in edges)))
            return
        for v in range(N):
            if v in verts:
                continue
            for u in verts:
                deg = sum(1 for a, b in edges if a == u or b == u)
                if deg < 3:
                    rec(edges + [(u, v)], verts | {v})

    if N == 1:
        return {()}
    rec([], {0})
    return out


def dual_key(adj: list[list[int]]) -> tuple:
    """Canonical (isomorphism-free enough for counting) key of a tree."""
    return tuple(sorted(tuple(sorted(nbrs)) for nbrs in adj))


def canonical(adj: list[list[int]]) -> str:
    """AHU-style canonical form of an unrooted tree."""
    if not adj:
        return "()"
    n = len(adj)
    seen = set()
    order = []

    def walk(u, p):
        seen.add(u)
        order.append(u)
        for w in adj[u]:
            if w != p:
                walk(w, u)

    walk(0, -1)
    order.reverse()
    rooted: dict[int, tuple] = {}
    for u in order:
        kids = sorted((rooted[w] for w in adj[u] if w in rooted))
        rooted[u] = ("(" + ",".join(kids) + ")")
    # reroot at a leaf
    leaf = min(range(n), key=lambda i: len(adj[i]))
    seen2 = set()
    order2 = []

    def walk2(u, p):
        seen2.add(u)
        order2.append(u)
        for w in adj[u]:
            if w != p:
                walk2(w, u)

    walk2(leaf, -1)
    order2.reverse()
    rooted2: dict[int, tuple] = {}
    for u in order2:
        kids = sorted((rooted2[w] for w in adj[u] if w in rooted2))
        rooted2[u] = ("(" + ",".join(kids) + ")")
    return rooted2[leaf]


def main() -> int:
    os.makedirs(RESULTS, exist_ok=True)
    rows = []
    failures_l1 = 0
    for n in range(3, N_MAX_ENUM + 1):
        max_faces_with_extra_cycles = 0
        best_alpha = 0
        duals: set[str] = set()
        for diagonals in enumerate_triangulations(n):
            tris = triangulation_triangle_count(diagonals, n)
            faces, adj = weak_dual(diagonals, n)
            # L1: 3-cycles == faces
            if len(tris) != len(faces) or set(tris) != {tuple(f) for f in faces}:
                failures_l1 += 1
            a = alpha_tree({i: adj[i] for i in range(len(faces))})
            best_alpha = max(best_alpha, a)
            duals.add(canonical(adj))
        dp = convex_nu_dp(n)[n]
        closed = convex_nu_closed_form(n)
        tree_bound = alpha_max_subcubic(n - 2)
        rows.append(
            {
                "n": n,
                "num_triangulations": CATALAN(n - 2),
                "max_alpha_weak_dual": best_alpha,
                "f_n_dp": dp,
                "f_n_closed_form": closed,
                "a_n_minus_2": tree_bound,
                "distinct_dual_isomorphism_classes": len(duals),
                "all_agree": int(best_alpha == dp == closed == tree_bound),
            }
        )
        print(
            f"n={n:2d}  max_alpha(weak dual)={best_alpha:2d}  f(n)={dp:2d}  "
            f"closed form={closed:2d}  a(n-2)={tree_bound:2d}  "
            f"dual classes={len(duals):5d}   {'OK' if rows[-1]['all_agree'] else 'MISMATCH'}",
            flush=True,
        )

    # L2 for small N: every subcubic tree on N vertices occurs as a weak dual.
    print()
    l2_ok = True
    for n in range(3, N_MAX_TREE + 1):
        N = n - 2
        duals = set()
        for diagonals in enumerate_triangulations(n):
            _faces, adj = weak_dual(diagonals, n)
            duals.add(canonical(adj))
        trees = {canonical(_adj_from_edges(N, e)) for e in all_subcubic_trees(N)}
        missing = trees - duals
        print(
            f"n={n:2d} (N={N}): subcubic trees on N vertices = {len(trees):6d}, "
            f"realised as weak duals = {len(duals):6d}, missing = {len(missing)}",
            flush=True,
        )
        if missing:
            l2_ok = False

    path = os.path.join(RESULTS, "weak_dual_reduction.csv")
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    print()
    print("L1 (every 3-cycle is a face) violations :", failures_l1)
    print("L2 (all subcubic trees are weak duals)  :", "holds for N<=%d" % N_MAX_TREE if l2_ok else "FAILS")
    ok = failures_l1 == 0 and l2_ok and all(r["all_agree"] for r in rows)
    print("OVERALL:", "all checks passed" if ok else "PROBLEM")
    return 0 if ok else 1


def _adj_from_edges(N: int, edges) -> list[list[int]]:
    adj = [[] for _ in range(N)]
    for a, b in edges:
        adj[a].append(b)
        adj[b].append(a)
    return adj


if __name__ == "__main__":
    raise SystemExit(main())